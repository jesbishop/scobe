const CATEGORY_KEYWORDS: Record<string, string[]> = {
  smileys: ['smileys', 'people', 'faces', 'hands', 'body'],
  animals: ['animals', 'nature', 'pets', 'weather', 'plants'],
  food: ['food', 'drink', 'fruit', 'meal', 'snack'],
  activity: ['activity', 'sports', 'games', 'music', 'arts'],
  travel: ['travel', 'places', 'transport', 'buildings', 'vehicles'],
  objects: ['objects', 'things', 'tools', 'tech'],
  symbols: ['symbols', 'signs', 'hearts', 'arrows', 'shapes'],
  flags: ['flags', 'countries']
}

export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase().replace(/\s+/g, ' ')
  if (!q) return EMOJI_CATEGORIES[0].emojis

  const terms = q.split(' ').filter(Boolean)
  const hits: Array<{ emoji: string; score: number }> = []

  for (const category of EMOJI_CATEGORIES) {
    if (category.id === 'recent') continue
    const categoryKeys = [
      category.id,
      category.label.toLowerCase(),
      ...(CATEGORY_KEYWORDS[category.id] || [])
    ]
    const categoryHit = terms.every((term) => categoryKeys.some((key) => key.includes(term)))

    for (const emoji of category.emojis) {
      const keywords = EMOJI_KEYWORDS[emoji] || []
      const haystack = keywords.join(' ')
      let score = 0

      if (categoryHit) score += 1
      if (emoji.includes(q)) score += 10

      for (const term of terms) {
        if (keywords.some((word) => word === term)) score += 8
        else if (keywords.some((word) => word.startsWith(term))) score += 5
        else if (haystack.includes(term)) score += 3
        else if (categoryKeys.some((key) => key.includes(term))) score += 1
        else {
          score = 0
          break
        }
      }

      if (score > 0) hits.push({ emoji, score })
    }
  }

  hits.sort((a, b) => b.score - a.score || a.emoji.localeCompare(b.emoji))
  return [...new Set(hits.map((item) => item.emoji))]
}
